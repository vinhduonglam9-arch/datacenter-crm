/**
 * Helper to generate CSS backgroundImage and backgroundSize from custom pattern settings
 */
export function buildCustomBackgroundCss(params: {
  backgroundColor: string;
  patternType: 'dots' | 'grid' | 'diagonal' | 'gradient' | 'solid';
  patternColor: string;
  spacing: number;
  dotRadius: number;
  gradientStops?: [string, string, string];
}): { backgroundImage: string; backgroundSize: string; previewBg: string } {
  const { backgroundColor, patternType, patternColor, spacing, dotRadius, gradientStops } = params;
  if (patternType === 'solid') {
    return {
      backgroundImage: 'none',
      backgroundSize: 'auto',
      previewBg: backgroundColor,
    };
  }
  if (patternType === 'gradient') {
    const stops = gradientStops || [backgroundColor, patternColor, backgroundColor];
    return {
      backgroundImage: `linear-gradient(135deg, ${stops[0]} 0%, ${stops[1]} 50%, ${stops[2]} 100%)`,
      backgroundSize: 'auto',
      previewBg: `linear-gradient(135deg, ${stops[0]}, ${stops[2]})`,
    };
  }
  if (patternType === 'grid') {
    return {
      backgroundImage: `linear-gradient(to right, ${patternColor} 1px, transparent 1px), linear-gradient(to bottom, ${patternColor} 1px, transparent 1px)`,
      backgroundSize: `${spacing}px ${spacing}px`,
      previewBg: backgroundColor,
    };
  }
  if (patternType === 'diagonal') {
    return {
      backgroundImage: `linear-gradient(45deg, ${patternColor} 25%, transparent 25%), linear-gradient(-45deg, ${patternColor} 25%, transparent 25%), linear-gradient(45deg, transparent 75%, ${patternColor} 75%), linear-gradient(-45deg, transparent 75%, ${patternColor} 75%)`,
      backgroundSize: `${spacing}px ${spacing}px`,
      previewBg: backgroundColor,
    };
  }
  // default: 'dots'
  return {
    backgroundImage: `radial-gradient(${patternColor} ${dotRadius}px, transparent ${dotRadius}px)`,
    backgroundSize: `${spacing}px ${spacing}px`,
    previewBg: backgroundColor,
  };
}

